import {
  Controller,
  Get,
  Post,
  Patch,
  Body,
  Param,
  Query,
  UseGuards,
  Req,
} from '@nestjs/common';
import { ApiTags, ApiOperation, ApiBearerAuth } from '@nestjs/swagger';
import { JwtAuthGuard } from '../auth/jwt-auth.guard';
import { RolesGuard } from '../auth/roles.guard';
import { Roles } from '../auth/roles.decorator';
import { Role } from '@prisma/client';
import { SecurityService } from './security.service';
import {
  ScanGatePassDto,
  RecordMovementDto,
  WalkInVisitorDto,
  VerifyVisitorCodeDto,
  ReportSecurityIncidentDto,
  SyncOfflineQueueDto,
} from './dto/security-movement.dto';

@ApiTags('Campus Gate Security Operations')
@ApiBearerAuth()
@UseGuards(JwtAuthGuard, RolesGuard)
@Controller('security')
export class SecurityController {
  constructor(private readonly securityService: SecurityService) {}

  // 1. SCAN DIGITAL QR CODE OR MANUAL ROLL NUMBER LOOKUP
  @Post('scan')
  @Roles(Role.SECURITY, Role.ADMIN, Role.SUPER_ADMIN, Role.WARDEN)
  @ApiOperation({ summary: 'Verify digital gate pass via QR code string or Roll Number' })
  async scanPass(@Body() body: ScanGatePassDto) {
    return this.securityService.scanPass(body);
  }

  // 2. CONCURRENCY-SAFE PHYSICAL EXIT RECORDING
  @Post('movement/exit')
  @Roles(Role.SECURITY, Role.ADMIN, Role.SUPER_ADMIN)
  @ApiOperation({ summary: 'Record student physical exit from campus gate' })
  async recordExit(@Body() body: RecordMovementDto, @Req() req: any) {
    return this.securityService.recordExit(body, req.user);
  }

  // 3. CONCURRENCY-SAFE PHYSICAL ENTRY RECORDING WITH LATE-RETURN DETECTION
  @Post('movement/entry')
  @Roles(Role.SECURITY, Role.ADMIN, Role.SUPER_ADMIN)
  @ApiOperation({ summary: 'Record student physical entry into campus with late-return detection' })
  async recordEntry(@Body() body: RecordMovementDto, @Req() req: any) {
    return this.securityService.recordEntry(body, req.user);
  }

  // 4. LIVE GATE STATS
  @Get('overview-stats')
  @Roles(Role.SECURITY, Role.ADMIN, Role.SUPER_ADMIN, Role.WARDEN)
  @ApiOperation({ summary: 'Get live gate operational KPI counters' })
  async getOverviewStats() {
    return this.securityService.getOverviewStats();
  }

  // 5. APPROVED GATE PASSES CATALOG
  @Get('passes/approved')
  @Roles(Role.SECURITY, Role.ADMIN, Role.SUPER_ADMIN, Role.WARDEN)
  @ApiOperation({ summary: 'Get list of warden-approved student gate passes' })
  async getApprovedPasses(
    @Query('date') date?: string,
    @Query('hostel') hostel?: string,
    @Query('status') status?: string,
    @Query('search') search?: string,
  ) {
    return this.securityService.getApprovedPasses({ date, hostel, status, search });
  }

  // 6. TURNSTILE MOVEMENT HISTORY
  @Get('movements/history')
  @Roles(Role.SECURITY, Role.ADMIN, Role.SUPER_ADMIN, Role.WARDEN)
  @ApiOperation({ summary: 'Get turnstile and gate physical movement history logs' })
  async getMovementsHistory(
    @Query('direction') direction?: string,
    @Query('search') search?: string,
  ) {
    return this.securityService.getMovementsHistory({ direction, search });
  }

  // 7. VERIFY VISITOR 6-DIGIT PRE-APPROVAL CODE
  @Post('visitors/verify-code')
  @Roles(Role.SECURITY, Role.ADMIN, Role.SUPER_ADMIN, Role.WARDEN)
  @ApiOperation({ summary: 'Verify 6-digit visitor invitation code generated by student' })
  async verifyVisitorCode(@Body() body: VerifyVisitorCodeDto) {
    return this.securityService.verifyVisitorCode(body);
  }

  // 8. WALK-IN VISITOR REGISTRATION
  @Post('visitors/walk-in')
  @Roles(Role.SECURITY, Role.ADMIN, Role.SUPER_ADMIN)
  @ApiOperation({ summary: 'Register walk-in campus visitor and issue guest pass' })
  async walkInVisitor(@Body() body: WalkInVisitorDto, @Req() req: any) {
    return this.securityService.walkInVisitor(body, req.user);
  }

  // 9. CHECK IN VISITOR
  @Patch('visitors/:id/checkin')
  @Roles(Role.SECURITY, Role.ADMIN, Role.SUPER_ADMIN)
  @ApiOperation({ summary: 'Check in pre-approved visitor upon arrival' })
  async checkInVisitor(
    @Param('id') id: string,
    @Body('badgeNumber') badgeNumber?: string,
    @Req() req?: any,
  ) {
    return this.securityService.checkInVisitor(id, badgeNumber, req?.user);
  }

  // 10. CHECK OUT VISITOR
  @Patch('visitors/:id/checkout')
  @Roles(Role.SECURITY, Role.ADMIN, Role.SUPER_ADMIN)
  @ApiOperation({ summary: 'Check out visitor upon departure from campus gate' })
  async checkOutVisitor(@Param('id') id: string, @Req() req?: any) {
    return this.securityService.checkOutVisitor(id, req?.user);
  }

  // 11. GET VISITORS LIST
  @Get('visitors')
  @Roles(Role.SECURITY, Role.ADMIN, Role.SUPER_ADMIN, Role.WARDEN)
  @ApiOperation({ summary: 'Get all visitor logs at the gate' })
  async getVisitors() {
    return this.securityService.getApprovedPasses({ status: 'ALL' });
  }

  // 12. REPORT SECURITY INCIDENT / UNAPPROVED EXIT ATTEMPT
  @Post('incidents')
  @Roles(Role.SECURITY, Role.ADMIN, Role.SUPER_ADMIN)
  @ApiOperation({ summary: 'Dispatch gate perimeter alert or unapproved exit incident' })
  async reportIncident(@Body() body: ReportSecurityIncidentDto, @Req() req: any) {
    return this.securityService.reportIncident(body, req.user);
  }

  // 13. IDEMPOTENT OFFLINE QUEUE SYNCHRONIZATION
  @Post('sync-offline-queue')
  @Roles(Role.SECURITY, Role.ADMIN, Role.SUPER_ADMIN)
  @ApiOperation({ summary: 'Synchronize locally queued offline movements upon reconnection' })
  async syncOfflineQueue(@Body() body: SyncOfflineQueueDto, @Req() req: any) {
    return this.securityService.syncOfflineQueue(body, req.user);
  }
}

